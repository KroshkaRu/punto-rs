#!/usr/bin/env python3
"""One-off generation of the bundled Smart statistics; never run by Cargo or the application."""
from collections import Counter
from hashlib import sha256
from math import log
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUPPORT = 33 ** 3


def triples(word):
    return (word[index:index + 3] for index in range(len(word) - 2))


def statistics(text, alphabet):
    lines = text.splitlines()
    int(lines[0])  # Hunspell's first line is the entry count, not a word.
    words = set()
    for line in lines[1:]:
        parts = line.split()
        if not parts:
            continue
        word = parts[0].split('/', 1)[0].lower()
        if len(word) >= 3 and all(char in alphabet for char in word):
            words.add(word)
    counts = Counter(triple for word in words for triple in triples(word))
    return words, counts


def main():
    destination = ROOT / 'assets' / 'smart'
    if (destination / 'trigrams.rs').exists():
        print('Smart statistics already exist; skipping without reading dictionaries.')
        return
    assert list(triples('example')) == ['exa', 'xam', 'amp', 'mpl', 'ple']
    words, counts = statistics('3\nExample/A\nexample/B\naaaaa\n', 'abcdefghijklmnopqrstuvwxyz')
    assert len(words) == 2 and counts['aaa'] == 3 and sum(counts.values()) == 8
    generated = ['// Generated by scripts/build-smart-stats.py. Counts and log probabilities; do not edit.\n']
    report = ['# Готовая статистика Smart\n',
              'Таблицы рассчитаны один раз скриптом `scripts/build-smart-stats.py`. '
              'Cargo и приложение этот скрипт не запускают.\n',
              'Каждое уникальное слово из статей `.dic` приводится к нижнему регистру. '
              'Флаги Hunspell и поля морфологии отбрасываются; словоформы по `.aff` не разворачиваются. '
              'В статистику входят буквенные слова A–Z и А–Я/Ё без внутренней пунктуации и цифр. '
              'Для слова длины n учитываются все n−2 перекрывающиеся тройки, включая повторы.\n',
              'Вес тройки: `ln((count + 1) / (total + 33³))`. Одинаковая область сглаживания '
              'для двух языков не даёт английскому преимущества из-за меньшего алфавита. '
              'Таблица содержит тройку, число вхождений и готовый вес; для отсутствующих троек задан отдельный вес.\n']
    for name, base, alphabet in [
        ('ENGLISH', 'en_US', 'abcdefghijklmnopqrstuvwxyz'),
        ('RUSSIAN', 'ru_RU', 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'),
    ]:
        path = Path('/usr/share/hunspell') / (base + '.dic')
        data = path.read_bytes()
        words, counts = statistics(data.decode('utf-8'), alphabet)
        total = sum(counts.values())
        assert total > 0 and max(counts.values()) < 2 ** 32
        normalizer = log(total + SUPPORT)
        generated.append(f'#[rustfmt::skip]\nconst {name}: Trigrams = Trigrams {{\n    missing: {-normalizer!r},\n    weights: &[\n')
        for triple, count in sorted(counts.items()):
            letters = ', '.join(repr(char) for char in triple)
            weight = log(count + 1) - normalizer
            generated.append(f'        ([{letters}], {count}, {weight!r}),\n')
        generated.append('    ],\n};\n\n')
        report.append(f'## {name}\n\nИсточник: `{path}`.\n\nSHA-256: `{sha256(data).hexdigest()}`.\n\n'
                      f'Уникальных слов: {len(words)}; троек: {len(counts)}; вхождений: {total}.\n')
        print(f'{name}: {len(words)} words, {len(counts)} trigrams, {total} occurrences')
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'trigrams.rs').write_text(''.join(generated), encoding='utf-8')
    (destination / 'README.md').write_text('\n'.join(report), encoding='utf-8')


if __name__ == '__main__':
    main()
